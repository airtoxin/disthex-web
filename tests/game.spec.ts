import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
const blueWin=[0,6,7,13,14,20,21,27,28,34,35,41,42]
const redWin=[0,21,1,22,2,23,3,24,4,25,5,26,6,27]
async function move(page:Page,index:number){
  const cell=page.locator(`[data-cell="${index}"]`)
  await expect(cell).toHaveAttribute('data-legal','true')
  await cell.click()
  await page.getByRole('button',{name:'ここに置く'}).click()
}
test.beforeEach(async({page})=>{ await page.goto('/') })
test('complete blue game, undo/redo, reload and rematch',async({page},info)=>{
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',message=>{ if(message.type()==='error')errors.push(message.text()) })
  await expect(page).toHaveTitle(/Disthex/)
  await expect(page.locator('[data-cell]')).toHaveCount(49)
  await expect(page.getByRole('button',{name:'ここに置く'})).toBeDisabled()
  for(const index of blueWin)await move(page,index)
  await expect(page.getByRole('status')).toContainText('プレイヤー1の勝利')
  await expect(page.locator('[data-legal="true"]')).toHaveCount(0)
  await expect(page.locator('.cell.winning')).toHaveCount(7)
  await page.screenshot({path:`test-results/${info.project.name}-winner.png`,fullPage:true})
  await page.getByRole('button',{name:'戻す',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('プレイヤー1の手番')
  await page.getByRole('button',{name:'やり直す',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('プレイヤー1の勝利')
  await page.reload()
  await expect(page.getByRole('status')).toContainText('プレイヤー1の勝利')
  await page.getByRole('button',{name:'もう一局あそぶ'}).click()
  await expect(page.locator('[data-legal="true"]')).toHaveCount(49)
  await expect(page.getByRole('button',{name:'戻す',exact:true})).toBeDisabled()
  expect(errors).toEqual([])
})
test('red connects left to right',async({page})=>{
  for(const index of redWin)await move(page,index)
  await expect(page.getByRole('status')).toContainText('プレイヤー2の勝利')
  await expect(page.locator('.cell.winning.red')).toHaveCount(7)
})
test('swap retains opening restriction, updates player, and supports undo',async({page})=>{
  await move(page,24)
  await expect(page.locator('[data-cell="23"]')).toHaveAttribute('aria-disabled','true')
  await page.locator('[data-cell="23"]').click({force:true})
  await expect(page.getByRole('button',{name:'ここに置く'})).toBeDisabled()
  await page.getByRole('button',{name:'色を交換する'}).click()
  await expect(page.getByRole('status')).toContainText('プレイヤー1の手番')
  await expect(page.locator('[data-cell="24"]')).toHaveAttribute('data-color','blue')
  await expect(page.locator('[data-cell="23"]')).toHaveAttribute('aria-disabled','true')
  await move(page,0)
  await expect(page.getByRole('status')).toContainText('プレイヤー2の手番')
  await expect(page.locator('[data-cell="23"]')).toHaveAttribute('data-legal','true')
  await page.getByRole('button',{name:'戻す',exact:true}).click()
  await page.getByRole('button',{name:'戻す',exact:true}).click()
  await expect(page.getByRole('button',{name:'色を交換する'})).toBeVisible()
  await expect(page.getByRole('status')).toContainText('プレイヤー2の手番')
})
test('all sizes, reset confirmation, rules, zoom and no horizontal page overflow',async({page},info)=>{
  for(const size of [9,11,7]){
    await page.getByLabel('盤のサイズ',{exact:true}).selectOption(String(size))
    await expect(page.locator('[data-cell]')).toHaveCount(size*size)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  }
  await move(page,24)
  await page.screenshot({path:`test-results/${info.project.name}-playing.png`,fullPage:true})
  await page.getByLabel('盤のサイズ',{exact:true}).selectOption('11')
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button',{name:'キャンセル'}).click()
  await expect(page.locator('[data-cell]')).toHaveCount(49)
  await expect(page.locator('[data-color="blue"]')).toHaveCount(1)
  await page.getByLabel('盤のサイズ',{exact:true}).selectOption('11')
  await page.getByRole('button',{name:'新しい対局を始める'}).click()
  await expect(page.locator('[data-cell]')).toHaveCount(121)
  await page.getByRole('button',{name:'盤面を拡大'}).click()
  await expect(page.locator('.board-scroller')).toHaveClass(/zoomed/)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
  await page.getByRole('button',{name:'全体を表示'}).click()
  await page.getByRole('button',{name:'遊び方',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('隣接する6方向')
  await expect(page.getByRole('link',{name:'作者によるオリジナルルールを読む'})).toHaveAttribute('href',/airtoxin\/my-games/)
  await page.getByRole('button',{name:'対局にもどる'}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.screenshot({path:`test-results/${info.project.name}-11x11.png`,fullPage:true})
})
test('keyboard cell selection and rules modal focus',async({page})=>{
  const first=page.locator('[data-cell="0"]')
  await first.focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.locator('[data-cell="1"]')).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button',{name:'ここに置く'})).toBeEnabled()
  await page.getByRole('button',{name:'ここに置く'}).click()
  await expect(page.locator('[data-cell="1"]')).toHaveAttribute('data-color','blue')
  const rules=page.getByRole('button',{name:'遊び方',exact:true})
  await rules.click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(rules).toBeFocused()
})
test('recovers safely from invalid saved history',async({page})=>{
  await page.evaluate(()=>localStorage.setItem('disthex.game.v1',JSON.stringify({version:1,size:7,cursor:2,events:[{type:'place',index:24},{type:'place',index:23}]})))
  await page.reload()
  await expect(page.locator('[data-legal="true"]')).toHaveCount(49)
})
