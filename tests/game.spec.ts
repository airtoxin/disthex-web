for (const size of [9,11]) test(`${size}×${size} board input, legal moves and connection`,async({page})=>{
  await page.getByLabel('盤のサイズ',{exact:true}).selectOption(String(size))
  for(let row=0;row<size;row++){
    await move(page,row*size)
    if(row<size-1) await move(page,row*size+size-1)
  }
  await expect(page.getByRole('status')).toContainText('プレイヤー1の勝利')
  await expect(page.locator('.cell.winning')).toHaveCount(size)
  await page.getByRole('button',{name:'もう一局あそぶ'}).click()
  await expect(page.locator('[data-legal="true"]')).toHaveCount(size*size)
  await page.locator(`[data-cell="${size*size-1}"]`).focus()
  await page.getByLabel('盤のサイズ',{exact:true}).selectOption('7')
  await expect(page.locator('[data-cell][tabindex="0"]')).toHaveCount(1)
})
test('swap and undone timeline survive reload, cancellation and branching',async({page})=>{
  await move(page,24)
  await page.getByRole('button',{name:'色を交換する'}).click()
  await move(page,0)
  await page.getByRole('button',{name:'戻す',exact:true}).click()
  const saved=await page.evaluate(()=>localStorage.getItem('disthex.game.v1'))
  await page.reload()
  await expect(page.getByRole('status')).toContainText('プレイヤー1の手番')
  await expect(page.getByRole('status')).toContainText('赤の石')
  await expect(page.locator('[data-cell="24"] .last-ring')).toHaveCount(1)
  await expect(page.locator('[data-cell="23"]')).toHaveAttribute('data-legal','false')
  await expect(page.locator('[data-cell="0"]')).toHaveAttribute('data-color','')
  await page.getByRole('button',{name:'新しい対局',exact:true}).click()
  await page.getByRole('button',{name:'キャンセル'}).click()
  expect(await page.evaluate(()=>localStorage.getItem('disthex.game.v1'))).toEqual(saved)
  await page.getByRole('button',{name:'やり直す',exact:true}).click()
  await page.reload()
  await expect(page.getByRole('status')).toContainText('プレイヤー2の手番')
  await expect(page.getByRole('status')).toContainText('青の石')
  await expect(page.locator('[data-cell="0"] .last-ring')).toHaveCount(1)
  await page.getByRole('button',{name:'戻す',exact:true}).click()
  await move(page,48)
  await expect(page.getByRole('button',{name:'やり直す',exact:true})).toBeDisabled()
  await page.reload()
  await expect(page.locator('[data-cell="48"]')).toHaveAttribute('data-color','red')
  await expect(page.locator('[data-cell="0"]')).toHaveAttribute('data-color','')
  await expect(page.getByRole('button',{name:'やり直す',exact:true})).toBeDisabled()
})

test('mandatory pass clears restrictions, persists, undoes and finishes the game',async({page},info)=>{
  await expect(page.getByRole('button',{name:'パスする',exact:true})).toHaveCount(0)
  const coordinates=[[0,2],[3,4],[6,4],[6,1],[6,5],[4,2],[6,3],[2,3],[2,1],[4,6],[3,3],[0,5],[6,2],[5,0],[3,0],[0,3],[3,1],[6,6],[2,4],[4,3],[0,0],[3,6],[1,6],[5,4],[2,6],[5,3],[1,0],[5,5],[2,0],[4,4],[1,5],[6,0],[2,2],[1,4],[4,5],[2,5],[5,2],[1,2],[5,1],[0,4],[1,1],[5,6],[0,6],[1,3],[3,2],[0,1],[3,5],[4,0]]
  await page.evaluate(coords=>localStorage.setItem('disthex.game.v1',JSON.stringify({version:1,size:7,events:coords.map(([r,c])=>({type:'place',index:r*7+c})),cursor:48})),coordinates)
  await page.reload()
  await expect(page.getByRole('status')).toContainText('プレイヤー1の手番')
  await expect(page.locator('[data-legal="true"]')).toHaveCount(0)
  await expect(page.locator('[data-cell="29"]')).toHaveAttribute('aria-disabled','true')
  const pass=page.getByRole('button',{name:'パスする',exact:true})
  await expect(pass).toBeEnabled()
  await page.screenshot({path:`test-results/${info.project.name}-mandatory-pass.png`,fullPage:true})
  await pass.click()
  await expect(page.getByRole('status')).toContainText('プレイヤー2の手番')
  await expect(page.locator('[data-cell="29"]')).toHaveAttribute('data-legal','true')
  await expect(page.locator('.last-ring')).toHaveCount(0)
  await expect(page.locator('.cell.restricted')).toHaveCount(0)
  await expect(pass).toHaveCount(0)
  await page.reload()
  await expect(page.locator('[data-cell="29"]')).toHaveAttribute('data-legal','true')
  await page.getByRole('button',{name:'戻す',exact:true}).click()
  await expect(pass).toBeEnabled()
  await expect(page.locator('[data-cell="28"] .last-ring')).toHaveCount(1)
  await page.getByRole('button',{name:'やり直す',exact:true}).click()
  await page.locator('.history summary').click()
  await expect(page.locator('.history')).toContainText('パス（合法手なし）')
  await move(page,29)
  await expect(page.getByRole('status')).toContainText('プレイヤー2の勝利')
  await expect(pass).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('status')).toContainText('プレイヤー2の勝利')
})
